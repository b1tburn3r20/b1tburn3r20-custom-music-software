    videoDetails: (ids) => invoke("youtube:video-details", ids),
    searchVideos: (q, filters) => invoke("youtube:search-videos", q, filters),
    searchPlaylists: (q, filters) => invoke("youtube:search-playlists", q, filters),
    publicPlaylist: (id) => invoke("youtube:public-playlist", id),
    lookupLink: (link) => invoke("youtube:lookup-link", link),
    authStatus: () => invoke("youtube:auth-status"),
    setAuth: (patch) => invoke("youtube:set-auth", patch),
